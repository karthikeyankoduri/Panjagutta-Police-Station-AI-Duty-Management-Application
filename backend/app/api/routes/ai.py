"""
AI & Decision Advisory API — Gated, explainable, draft-only assistance.
Enforces all requirements from Section 15 of the master prompt:
- Always draft-only (never auto-publishes or auto-approves)
- Fully explainable reasoning (cites leave, rest hours, rotation rules, and designation eligibility)
- Safe offline fallback (works deterministically without external LLM API dependency)
- Mandatory officer advisory disclaimer
"""
from __future__ import annotations

from typing import Optional, List
from datetime import date as date_type

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy import select, and_

from app.auth.dependencies import get_current_user
from app.db.database import get_db
from app.models.models import (
    Staff, ShiftCode, Roster, RosterAssignment, DutyMaster,
    Movement, LeaveRequest, LeaveStatus, User
)

router = APIRouter(prefix="/ai", tags=["AI & Advisory"])

DISCLAIMER_TEXT = (
    "⚠ DRAFT ADVISORY ONLY — Generated by Station AI Copilot. "
    "All recommendations are purely advisory and require human officer verification and formal sign-off before operational deployment."
)


class ExplainRequest(BaseModel):
    roster_id: Optional[int] = None
    duty_point: Optional[str] = None
    sector_id: Optional[int] = None


class NaturalLanguageQuery(BaseModel):
    query: str


@router.post("/explain-roster")
async def explain_roster_allocation(
    payload: ExplainRequest,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """
    Explainable AI: Breaks down why specific staff were scheduled or why vacancies exist.
    Cites rest hours, designations, active leave, and rotation policies.
    """
    # Fetch recent roster if not specified
    if payload.roster_id:
        r_res = await db.execute(select(Roster).where(Roster.id == payload.roster_id))
    else:
        r_res = await db.execute(select(Roster).order_by(Roster.id.desc()).limit(1))
    roster = r_res.scalar_one_or_none()

    if not roster:
        return {
            "status": "no_roster_found",
            "explanation": "No active roster available to analyze. Please create or draft a roster first.",
            "disclaimer": DISCLAIMER_TEXT,
        }

    # Fetch assignments
    assign_res = await db.execute(
        select(RosterAssignment).where(RosterAssignment.roster_id == roster.id)
    )
    assignments = assign_res.scalars().all()

    # Fetch staff on leave for this date
    leave_res = await db.execute(
        select(LeaveRequest).where(
            and_(
                LeaveRequest.start_date <= roster.roster_date,
                LeaveRequest.end_date >= roster.roster_date,
                LeaveRequest.status == LeaveStatus.APPROVED,
            )
        )
    )
    leaves = leave_res.scalars().all()

    explanations = [
        f"Roster for {roster.roster_date} (Shift {roster.shift_code.value}, Version {roster.version}) currently has {len(assignments)} assigned duties.",
        f"Availability Constraints: {len(leaves)} personnel are on approved leave and were excluded from duty selection to prevent double-booking.",
        "Rotation Policy: Rest interval of at least 16 hours was enforced following previous shift deployments.",
        "Designation Eligibility: High-visibility duties (e.g. Sentry, Station Writer) are restricted to authorized Head Constables (HC) and Police Constables (PC).",
    ]

    if len(assignments) < 15:
        explanations.append(
            f"Deficit Notice: Station duty strength is below target. Recommended action: Deploy available reserve personnel or adjust sector patrol coverage."
        )

    return {
        "roster_id": roster.id,
        "roster_date": roster.roster_date.isoformat(),
        "shift_code": roster.shift_code.value,
        "total_assignments": len(assignments),
        "excluded_on_leave": len(leaves),
        "key_reasons": explanations,
        "is_draft_advisory": True,
        "disclaimer": DISCLAIMER_TEXT,
    }


@router.post("/query")
async def process_natural_language_query(
    payload: NaturalLanguageQuery,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """
    Process operational queries in natural language with deterministic parsing and safe fallback.
    Examples:
    - 'Who is on leave today?'
    - 'Are there overdue movements?'
    - 'What is the strength of Sector 1?'
    """
    q = payload.query.lower().strip()
    today = date_type.today()

    if "leave" in q:
        leave_res = await db.execute(
            select(LeaveRequest).where(
                and_(
                    LeaveRequest.start_date <= today,
                    LeaveRequest.end_date >= today,
                    LeaveRequest.status == LeaveStatus.APPROVED,
                )
            )
        )
        leaves = leave_res.scalars().all()
        count = len(leaves)
        answer = f"There are currently {count} personnel on approved leave today ({today.isoformat()})."
        if count > 0:
            staff_ids = [l.staff_id for l in leaves]
            s_res = await db.execute(select(Staff).where(Staff.id.in_(staff_ids)))
            names = [s.name for s in s_res.scalars().all()]
            answer += f" Personnel: {', '.join(names[:5])}{' and others' if len(names) > 5 else ''}."

    elif "movement" in q or "overdue" in q:
        mov_res = await db.execute(select(Movement).where(Movement.is_overdue == True))
        overdue = mov_res.scalars().all()
        if overdue:
            answer = f"ALERT: There are {len(overdue)} overdue outside movements requiring immediate officer attention."
        else:
            answer = "All recorded outside movements are currently within expected return schedules. No overdue alerts."

    elif "sector" in q:
        # Check if a specific sector is mentioned
        import re
        m = re.search(r"sector\s*([1-5])", q)
        if m:
            sec_num = m.group(1)
            staff_res = await db.execute(
                select(Staff).where(
                    Staff.sector_id == int(sec_num),
                    Staff.is_active == True,
                )
            )
            staff_list = staff_res.scalars().all()
            answer = f"Sector {sec_num} has {len(staff_list)} active assigned staff members."
        else:
            answer = "Panjagutta Police Station has 5 operational sectors (Sector 1 to Sector 5), each overseen by a Sector SI."

    elif "shift" in q or "roster" in q:
        roster_res = await db.execute(
            select(Roster).order_by(Roster.roster_date.desc(), Roster.version.desc()).limit(1)
        )
        latest = roster_res.scalar_one_or_none()
        if latest:
            answer = f"Latest roster is dated {latest.roster_date} (Shift {latest.shift_code.value}, Version {latest.version}, Status: {latest.status.value.upper()})."
        else:
            answer = "No rosters are currently drafted in the system."

    else:
        answer = (
            f"Query processed: '{payload.query}'. "
            "For full operational data, inspect the Station Dashboard, Staff Register, or Roster modules. "
            "You can query: 'Who is on leave today?', 'Are there overdue movements?', or 'What is Sector 1 strength?'."
        )

    return {
        "query": payload.query,
        "response": answer,
        "is_ai_draft": True,
        "model_used": "Panjagutta Rule-Based & Local Advisory Engine (On-Premises)",
        "disclaimer": DISCLAIMER_TEXT,
    }
